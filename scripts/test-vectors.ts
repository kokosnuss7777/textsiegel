// Generates spec/test-vectors.json: fixed inputs and outputs against which ports to other languages
// (Python, PHP, …) can be checked. Invisible characters are written as \uXXXX escapes.
//
//   node scripts/test-vectors.ts
//
// Deterministic: contentKey, base-3 encoding, signature 0xF2 (with a fixed response ID) and Choice-Point-Mark.
// For 0xF3 (random response ID and salt) the file contains a signed record together with the text and the
// public key; there only the verification result is checked.

import { createPrivateKey, createPublicKey } from "node:crypto";
import { writeFileSync } from "node:fs";
import { markResponse, markText, verify } from "../src/cpmark.ts";
import { contentKey, encodeSignature, toDigits } from "../src/signature.ts";
import { createProvenance, verifyPublic } from "../src/provenance.ts";

/** Ed25519 key from a fixed seed (PKCS#8 prefix + 32 bytes) – for test vectors only. */
export function testKey() {
  const seed = Buffer.alloc(32, 7);
  const privateKey = createPrivateKey({ key: Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]), format: "der", type: "pkcs8" });
  return { privateKey, publicKey: createPublicKey(privateKey) };
}

const KEY = "test-vector-key";
const CUSTOMER_ID = 4242;
const RESPONSE_ID = "0a0b0c0d0e0f";
// German sample sentences: the Choice-Point-Mark classes are defined for German text.
const TEXTS = [
  "Die Lieferung dauert zwei Tage.",
  "Bestellungen bis 14 Uhr verschicken wir zudem am selben Tag. Die Versandkosten betragen ca. 5 € – ab 49 € ist der Versand kostenlos.",
  "## Ablauf\n\n1. Wählen Sie **Abholung vor Ort**.\n2. Wir melden uns „sofort“ per E-Mail.",
];

export async function buildVectors() {
  const { privateKey, publicKey } = testKey();
  const rid = Buffer.from(RESPONSE_ID, "hex");
  const sig = { key: KEY, signature: { customerId: CUSTOMER_ID, responseId: rid } };
  const customers = [{ id: CUSTOMER_ID, key: KEY }];
  const marker = (sentence: string) => encodeSignature({ key: KEY, customerId: CUSTOMER_ID, responseId: rid }, sentence).vs;

  const provenance = createProvenance({ keyId: 1, privateKey, customer: "customer-test-vector", model: "test-model" });
  const publicText = markResponse(TEXTS[1], { key: KEY, provenance }).text;
  const record = provenance.finish();
  const fetchRecord = async (id: string) => (id === record.record.responseId ? record : undefined);

  return {
    description: "Test vectors for ports of textsiegel. Generated by scripts/test-vectors.ts.",
    contentKey: ["Die Lieferung dauert zwei Tage.", "1. Wählen Sie **Abholung vor Ort**.", "- Ab 49 €: versandkostenfrei", "„Größe“ – ca. 5 cm…", "ﬁ Ligatur (NFKC)"].map(
      (input) => ({ input, output: contentKey(input) }),
    ),
    base3: [
      { bytesHex: "00".repeat(16), output: toDigits(Array(16).fill(0)) },
      { bytesHex: "ff".repeat(16), output: toDigits(Array(16).fill(255)) },
      { bytesHex: "f30101020304050607080003deadbeef", output: toDigits([...Buffer.from("f30101020304050607080003deadbeef", "hex")]) },
    ],
    signature0xF2: TEXTS.map((sentence) => ({ key: KEY, customerId: CUSTOMER_ID, responseIdHex: RESPONSE_ID, sentence, marker: marker(sentence) })),
    choicePointMark: TEXTS.map((input) => ({ key: KEY, input, output: markText(input, { key: KEY }).text })),
    markResponse0xF2: TEXTS.map((input) => {
      const output = markResponse(input, sig).text;
      return { key: KEY, customerId: CUSTOMER_ID, responseIdHex: RESPONSE_ID, input, output, verdict: verify(output, customers).verdict };
    }),
    verify0xF2: [
      { description: "moved to a foreign sentence", text: "Die Erde ist eine Scheibe." + marker("Die Lieferung dauert zwei Tage.") },
      { description: "unchanged", text: "Die Lieferung dauert zwei Tage." + marker("Die Lieferung dauert zwei Tage.") },
    ].map((v) => ({ ...v, customers, verdict: verify(v.text, customers).verdict })),
    provenance0xF3: {
      publicKeyJwk: publicKey.export({ format: "jwk" }),
      keyId: 1,
      record,
      text: publicText,
      result: await verifyPublic(publicText, fetchRecord, { 1: publicKey }),
    },
  };
}

const escapeUnicode = (json: string) => json.replace(/[‌‍⁠︀-️  ]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("../spec/test-vectors.json", import.meta.url), escapeUnicode(JSON.stringify(await buildVectors(), null, 2)) + "\n");
  console.log("spec/test-vectors.json written");
}
